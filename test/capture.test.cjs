const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises'),os=require('node:os'),path=require('node:path');
const {template,validation,createTemplates}=require('../src/capture.cjs');
const {createProjects}=require('../src/projects.cjs');
async function embeddedIndex(buffer){
 const lib=require('pdf-lib'),doc=await lib.PDFDocument.load(buffer);
 const names=doc.catalog.lookup(lib.PDFName.of('Names'),lib.PDFDict).lookup(lib.PDFName.of('EmbeddedFiles'),lib.PDFDict).lookup(lib.PDFName.of('Names'),lib.PDFArray);
 const file=doc.context.lookup(names.get(1),lib.PDFDict),stream=file.lookup(lib.PDFName.of('EF'),lib.PDFDict).lookup(lib.PDFName.of('F'),lib.PDFRawStream);
 return JSON.parse(Buffer.from(lib.decodePDFRawStream(stream).decode()).toString('utf8'));
}
const model=()=>({name:'Ficha de matrícula',fields:[{id:'matricula',name:'Matrícula',type:'identifier',digits:8,required:true,region:{x:.45,y:.1,width:.5,height:.5}}]});
test('modelos validam regiões e preservam versões anteriores',async t=>{
 const root=await fs.mkdtemp(path.join(os.tmpdir(),'cotrim-models-'));t.after(()=>fs.rm(root,{recursive:true,force:true}));
 const store=createTemplates(root),first=await store.save(model());
 const second=await store.save({...first,name:'Ficha atualizada'});
 assert.equal(first.version,1);assert.equal(second.version,2);assert.equal(second.id,first.id);
 assert.equal((await createTemplates(root).list()).length,1);
 assert.equal(first.name,'Ficha de matrícula');
 for(const region of [{x:-.1,y:0,width:.2,height:.2},{x:.9,y:0,width:.2,height:.2},{x:0,y:0,width:0,height:.2}])assert.throws(()=>template({...model(),fields:[{...model().fields[0],region}]}),/região/);
 assert.throws(()=>template({...model(),fields:[model().fields[0],model().fields[0]]}),/únicos/);
 assert.equal(validation(model().fields[0],'00125473'),'');
 assert.match(validation(model().fields[0],'125473'),/8 dígitos/);
 assert.match(validation({type:'cpf'},'111.111.111-11'),/CPF/);
 assert.equal(validation({type:'cpf'},'529.982.247-25'),'');
 assert.match(validation({type:'date'},'31/02/2026'),/data válida/);
});
test('OCR real por zona, correção, reabertura e indexação incorporada ao PDF sem perder zeros',async t=>{
 const root=await fs.mkdtemp(path.join(os.tmpdir(),'cotrim-zones-'));t.after(()=>fs.rm(root,{recursive:true,force:true}));
 const output=path.join(root,'output');await fs.mkdir(output);
 const sharp=require('sharp'),image=await sharp(Buffer.from('<svg width="1400" height="600"><rect width="1400" height="600" fill="white"/><text x="60" y="170" font-family="Arial" font-size="70">99999999</text><text x="720" y="170" font-family="Arial" font-size="70">00125478</text></svg>')).jpeg().toBuffer();
 const store=createProjects(root),project=await store.create({name:'Teste',port:9880,dpi:300,source:'Feeder',outputs:[output],captureTemplate:model()});
 await store.append(project.id,image);
 const read=await store.captureData(project.id,0);assert.equal(read.error,'');assert.equal(read.fields[0].recognized,'00125478');assert.equal(read.fields[0].value,'00125478');
 const saved=await store.saveCapture(project.id,0,[{id:'matricula',value:'00125473',reviewed:true}],read.revision);
 assert.equal(saved.fields[0].recognized,'00125478');assert.equal(saved.fields[0].corrected,true);assert.equal(saved.needsReview,false);
 await assert.rejects(store.saveCapture(project.id,0,[{id:'matricula',value:'9',reviewed:true}],read.revision),/mudaram/);
 assert.equal((await createProjects(root).captureData(project.id,0)).fields[0].value,'00125473');
 assert.equal((await store.capture(project.id,0)).fields[0].value,'00125473');
 await store.exportAll(project.id);await store.exportAll(project.id);
 let files=await fs.readdir(output);assert.equal(files.length,1);assert.ok(files[0].endsWith('.pdf'));assert.equal(files.some(f=>f.endsWith('.json')),false);
 const index=await embeddedIndex(await fs.readFile(path.join(output,files[0])));assert.equal(index.fields[0].value,'00125473');assert.equal(index.template.version,1);
 const preview=await require('../src/capture.cjs').preview('data:image/jpeg;base64,'+image.toString('base64'),model().fields[0],300);
 assert.equal(preview.value,'00125478');assert.equal(preview.error,'');
 await assert.rejects(require('../src/capture.cjs').preview('https://example.com/image.jpg',model().fields[0],300),/folha de exemplo/);
 await assert.rejects(store.update(project.id,{namingMode:'ocr',namingFieldId:'missing'}),/Selecione um campo/);
 await store.update(project.id,{namingMode:'ocr',namingFieldId:'matricula'});
 assert.equal((await store.pageOutput(project.id,0)).filename,'00125473.pdf');
 await store.exportAll(project.id);await store.exportAll(project.id);assert.equal((await fs.readdir(output)).length,2);
 const rereview=await store.saveCapture(project.id,0,[{id:'matricula',value:'00125473',reviewed:false}],saved.revision);
 assert.equal((await store.pageOutput(project.id,0)).filename,'00125473-2.pdf');
 await store.exportAll(project.id);await store.exportAll(project.id);assert.equal((await fs.readdir(output)).length,3);
 assert.equal((await embeddedIndex(await fs.readFile(path.join(output,'00125473.pdf')))).fields[0].reviewed,true);
 await store.saveCapture(project.id,0,[{id:'matricula',value:'00125474',reviewed:true}],rereview.revision);
 assert.equal((await store.pageOutput(project.id,0)).filename,'00125474.pdf');
 await store.transformPage(project.id,0,async b=>b);
 const changed=await store.captureData(project.id,0);assert.equal(changed.fields[0].value,'00125474');assert.equal(changed.fields[0].reviewed,false);assert.equal(changed.imageChanged,true);
 const fallback=await store.pageOutput(project.id,0);assert.match(fallback.filename,/^pagina-/);assert.match(fallback.warning,/campo OCR/);
 await assert.rejects(store.saveCapture(project.id,0,[{id:'matricula',value:'9',reviewed:true}],saved.revision),/mudaram/);
 await store.clear(project.id);assert.deepEqual(await fs.readdir(path.join(root,project.id)),['project.json']);
});

 const output=path.join(dir,'output');await fs.mkdir(output);
 const store=createProjects(dir),project=await store.create({...options,outputs:[output]});
 const photo=await sharp(Buffer.from('<svg width="800" height="700"><rect width="800" height="700" fill="#303030"/><path d="M160 70 L650 120 L600 630 L110 570 Z" fill="#ddd"/><path d="M220 240 L510 265" stroke="#333" stroke-width="8"/></svg>')).jpeg().toBuffer();
 const old=await store.append(project.id,photo);await store.exportAll(project.id);

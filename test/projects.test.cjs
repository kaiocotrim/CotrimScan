test('rotação persiste imagem, renova exportação e preserva outros documentos',async t=>{
 const sharp=require('sharp');
 const dir=await fs.mkdtemp(path.join(os.tmpdir(),'cotrim-rotate-'));t.after(()=>fs.rm(dir,{recursive:true,force:true}));
 const output=path.join(dir,'output');await fs.mkdir(output);
 const store=createProjects(dir),project=await store.create({...options,outputs:[output]});
 const image=await sharp({create:{width:40,height:20,channels:3,background:'red'}}).jpeg().toBuffer();
 const first=await store.append(project.id,image);await store.append(project.id,image);
 await store.exportAll(project.id);
 await fs.writeFile(path.join(dir,project.id,`${first}-cached.pdf`),'old signed PDF');
 await assert.rejects(store.rotate(project.id,0,45),/Rotação inválida/);
 await assert.rejects(store.rotate(project.id,9,90),/Página inválida/);
 for(const angle of [90,180,270]){
  const before=await sharp((await store.open(project.id)).pages[0]).metadata();
  await store.rotate(project.id,0,angle);
  const opened=await createProjects(dir).open(project.id),after=await sharp(opened.pages[0]).metadata();
  assert.equal(after.width,angle===180?before.width:before.height);
  assert.equal(after.height,angle===180?before.height:before.width);
  assert.deepEqual(opened.pages[1],image);
 }
 await assert.rejects(fs.stat(path.join(dir,project.id,`${first}-cached.pdf`)),{code:'ENOENT'});
 await store.exportAll(project.id);assert.equal((await fs.readdir(output)).length,3);
 assert.equal((await store.open(project.id)).pages.length,2);
});

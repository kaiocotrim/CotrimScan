 const {PDFDocument,PDFName,PDFRawStream}=require('pdf-lib'),pdf=await PDFDocument.load(first.buffer);
 const embedded=pdf.context.enumerateIndirectObjects().map(([,o])=>o).find(o=>o instanceof PDFRawStream&&o.dict.get(PDFName.of('Filter'))?.toString()==='/DCTDecode');
